// Turns a failed AI request into a warning shown on the course page. The
// PocketBase route answers with a message meant for the user.
function aiErrorMessage(error: unknown) {
  return (
    (error as ClientResponseError)?.response?.message ??
    "Sikertelen kérés a Gemini API felé, próbáld újra később."
  );
}

export async function clientLoader({ params }: Route.LoaderArgs) {
  const { courseId, ai } = params;

  if (courseId) {
    const record = await pb.collection("course_instance").getOne(courseId, {
      expand: "course",
    });

    if (ai === "summary" || ai === "flashcards") {
      try {
        // Generated by PocketBase (pb_hooks/ai.pb.js), which holds the Gemini API key.
        const { summary = null, flashcards = null } = await pb.send(
          `/api/lms/course-instances/${courseId}/ai/${ai}`,
          { method: "POST" }
        );

        return { record, summaryResult: summary, flashcards };
      } catch (error) {
        console.error(error);
        return { record, summaryResult: null, flashcards: null, aiError: aiErrorMessage(error) };
      }
    }

    const summaryResult = null,
      flashcards = null;

    return { record, summaryResult, flashcards };
  } else {
    const users_courses = await pb.collection("course_instance").getFullList({
      filter: `students ~ "${pb.authStore.record.id}"`,
      expand: "course,teacher",
    });

    return {
      record: null,
      summaryResult: null,
      flashcards: null,
      users_courses: users_courses,
    };
  }

  return null;
}

